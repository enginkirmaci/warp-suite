//! Build facts and the Windows resource block come from the shared kit; the
//! icon path is relative to this app's manifest directory. The generated asset
//! table stays here: it needs the app's own `assets/` tree, not a suite fact.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    warpui_kit_build::emit(
        warpui_kit_build::AppInfo::new("Warp Station", "Repository workbench", "warp-station.exe")
            .with_icon("../../packaging/windows/warp-station.ico"),
    );
    embed_assets();
}

// This used to be rust-embed, which silently drops every file whose
// std::fs::canonicalize fails (filter_map + ok()?). Mapped/subst Windows
// volumes can fail exactly that call for every path (os error 1005) while
// plain reads keep working - the embedded set then comes out empty and the
// UI runs without any icons. Generate the table with plain filesystem reads
// instead: include_bytes! needs no canonicalization. Absolute paths are
// required because the generated file lives in OUT_DIR.
fn embed_assets() {
    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let assets_dir = manifest_dir.join("assets");
    println!("cargo:rerun-if-changed={}", assets_dir.display());

    let mut files = Vec::new();
    collect(&assets_dir, &assets_dir, &mut files);
    files.sort();
    if files.is_empty() {
        panic!(
            "no assets found under {} - refusing to build with an empty asset set",
            assets_dir.display()
        );
    }

    let mut generated =
        String::from("// generated by build.rs from the assets/ tree - do not edit\n");
    generated.push_str("static EMBEDDED_FILES: &[(&str, &[u8])] = &[\n");
    for (key, path) in &files {
        writeln!(
            generated,
            "    ({key:?}, include_bytes!({path:?})),",
            path = path.display().to_string()
        )
        .unwrap();
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let target = out.join("embedded_assets.rs");
    fs::write(&target, generated).expect("write embedded_assets.rs");
    println!("cargo:rerun-if-changed={}", target.display());
}

fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(error) => panic!("read {}: {error}", dir.display()),
    };
    for entry in entries {
        let entry = entry.expect("dir entry");
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, files);
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .expect("asset under root")
            .components()
            .map(|part| part.as_os_str().to_string_lossy().into_owned())
            .collect::<Vec<_>>()
            .join("/");
        files.push((relative, path));
    }
}
