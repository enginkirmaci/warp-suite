#!/bin/sh
# Build the kit release artifacts under dist/kits/.
#
#   warp-suite-kits-<version>.tar.gz   the kits source snapshot
#   kits.toml                          version, build, commit and tag
#   SHA256SUMS                         checksums of the two files above
#
# Every local run consumes the next kit build number (version.py build bump).
# A release job passes --no-bump and publishes the number already in the tag's
# version.toml, so re-running a tag cannot mint a second number.
set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
root=$(CDPATH= cd -- "$here/../.." && pwd)

bump=1
for arg in "$@"; do
    case "$arg" in
        --no-bump) bump=0 ;;
        *)
            echo "usage: kit-build.sh [--no-bump]" >&2
            exit 2
            ;;
    esac
done

py=python3
command -v "$py" >/dev/null 2>&1 || py=python

if [ "$bump" = 1 ]; then
    "$py" "$root/scripts/meta/version.py" build bump >/dev/null
fi

facts=$("$py" "$root/scripts/meta/version.py" show --json)
version=$(printf '%s' "$facts" | "$py" -c 'import json,sys; print(json.load(sys.stdin)["version"])')
build=$(printf '%s' "$facts" | "$py" -c 'import json,sys; print(json.load(sys.stdin)["build"])')
commit=$(printf '%s' "$facts" | "$py" -c 'import json,sys; print(json.load(sys.stdin)["commit"])')
tag="kits-v$version"

out="$root/dist/kits"
mkdir -p "$out"
archive="warp-suite-kits-$version.tar.gz"

git -C "$root" archive \
    --format=tar.gz \
    --prefix="warp-suite-kits-$version/" \
    --output="$out/$archive" \
    HEAD kits Cargo.toml Cargo.lock rust-toolchain.toml .cargo

cat > "$out/kits.toml" <<EOF
# Generated by scripts/build/kit-build.sh. App repos pin the tag, not this file.
[kit]
version = "$version"
build = $build
commit = "$commit"
tag = "$tag"
EOF

(
    cd "$out"
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$archive" kits.toml > SHA256SUMS
    else
        shasum -a 256 "$archive" kits.toml > SHA256SUMS
    fi
)

echo "kits $version build $build -> $out/$archive"
